@contextmanager
def db():
    with psycopg.connect(DB, row_factory=dict_row) as con:
        yield con

def init_db():
    with db() as c:
        for statement in [
            "CREATE TABLE IF NOT EXISTS users(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT UNIQUE NOT NULL, token_hash TEXT UNIQUE NOT NULL)",
            "CREATE TABLE IF NOT EXISTS secrets(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, owner_id BIGINT NOT NULL REFERENCES users(id), nonce BYTEA NOT NULL, ciphertext BYTEA NOT NULL, version INTEGER NOT NULL DEFAULT 1, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL, UNIQUE(owner_id,name))",
            "CREATE TABLE IF NOT EXISTS grants(secret_id BIGINT NOT NULL REFERENCES secrets(id) ON DELETE CASCADE, user_id BIGINT NOT NULL REFERENCES users(id), permission TEXT NOT NULL CHECK(permission IN ('read','write')), UNIQUE(secret_id,user_id))",
            "CREATE TABLE IF NOT EXISTS audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id BIGINT REFERENCES users(id), action TEXT NOT NULL, secret_id BIGINT, outcome TEXT NOT NULL, at TIMESTAMPTZ NOT NULL)"
        ]: c.execute(statement)

@app.on_event('startup')
def startup(): init_db()

def now(): return datetime.now(timezone.utc).isoformat()
def digest(t): return hashlib.sha256(t.encode()).hexdigest()
def actor(authorization):
    if not authorization or not authorization.startswith('Bearer '): raise HTTPException(401,'Bearer token required')
    token = authorization[7:]
    with db() as c:
        row = c.execute('SELECT id,username FROM users WHERE token_hash=%s',(digest(token),)).fetchone()
    if not row: raise HTTPException(401,'Invalid token')
    return row

def log(c, who, action, sid, outcome):
    c.execute('INSERT INTO audit(actor_id,action,secret_id,outcome,at) VALUES(%s,%s,%s,%s,%s)',(who,action,sid,outcome,now()))

def access(c, sid, uid, level):
    s = c.execute('SELECT * FROM secrets WHERE id=%s',(sid,)).fetchone()
    if not s: raise HTTPException(404,'Secret not found')
    if s['owner_id'] != uid:
        g = c.execute('SELECT permission FROM grants WHERE secret_id=%s AND user_id=%s',(sid,uid)).fetchone()
        if not g or (level == 'write' and g['permission'] != 'write'):
            log(c,uid,'access',sid,'denied')
            c.commit()
            raise HTTPException(403,'Permission denied')
    return s

def encrypt(value, sid, version):
    nonce = os.urandom(12)
    aad = f'{sid}:{version}'.encode()
    return nonce, AESGCM(KEY).encrypt(nonce,value.encode(),aad)
def decrypt(s): return AESGCM(KEY).decrypt(bytes(s['nonce']),bytes(s['ciphertext']),f"{s['id']}:{s['version']}".encode()).decode()

class Register(BaseModel):
    username: str = Field(min_length=3,max_length=50,pattern=r'^[a-zA-Z0-9_-]+$')
class SecretInput(BaseModel):
    name: str = Field(min_length=1,max_length=100)
    value: str = Field(min_length=1,max_length=10000)
class ValueInput(BaseModel):
    value: str = Field(min_length=1,max_length=10000)
class GrantInput(BaseModel):
    username: str
    permission: str = Field(pattern='^(read|write)$')

@app.post('/api/register',status_code=201)
def register(data:Register):
    token=secrets.token_urlsafe(32)
    with db() as c:
        try: c.execute('INSERT INTO users(username,token_hash) VALUES(%s,%s)',(data.username,digest(token)))
        except UniqueViolation: raise HTTPException(409,'Username already exists')
    return {'username':data.username,'token':token,'warning':'Save this token now; it cannot be recovered.'}
