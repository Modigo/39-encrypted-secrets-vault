@app.get('/api/secrets/{sid}')
def read_secret(sid:int,authorization:str|None=Header(None)):
    a=actor(authorization)
    with db() as c:
        s=access(c,sid,a['id'],'read')
        try: value=decrypt(s)
        except Exception: raise HTTPException(500,'Unable to decrypt secret')
        log(c,a['id'],'read',sid,'ok')
        return {'id':sid,'name':s['name'],'value':value,'version':s['version']}
@app.put('/api/secrets/{sid}/rotate')
def rotate(sid:int,data:ValueInput,authorization:str|None=Header(None)):
    a=actor(authorization)
    with db() as c:
        s=access(c,sid,a['id'],'write');v=s['version']+1;n,ct=encrypt(data.value,sid,v)
        updated=c.execute('UPDATE secrets SET nonce=%s,ciphertext=%s,version=%s,updated_at=%s WHERE id=%s AND version=%s',(n,ct,v,now(),sid,s['version'])).rowcount
        if updated != 1: raise HTTPException(409,'Secret was updated concurrently; reload and retry')
        log(c,a['id'],'rotate',sid,'ok')
        return {'id':sid,'version':v}
@app.post('/api/secrets/{sid}/grants')
def grant(sid:int,data:GrantInput,authorization:str|None=Header(None)):
    a=actor(authorization)
    with db() as c:
        s=access(c,sid,a['id'],'read')
        if s['owner_id']!=a['id']: raise HTTPException(403,'Only owner can grant access')
        u=c.execute('SELECT id FROM users WHERE username=%s',(data.username,)).fetchone()
        if not u: raise HTTPException(404,'User not found')
        if u['id']==a['id']: raise HTTPException(400,'Owner already has full access')
        c.execute('INSERT INTO grants(secret_id,user_id,permission) VALUES(%s,%s,%s) ON CONFLICT(secret_id,user_id) DO UPDATE SET permission=excluded.permission',(sid,u['id'],data.permission))
        log(c,a['id'],'grant',sid,'ok')
    return {'status':'ok'}
