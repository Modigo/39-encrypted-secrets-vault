def list_secrets(authorization:str|None=Header(None)):
    a=actor(authorization)
    with db() as c:
        rows=c.execute('''SELECT DISTINCT s.id,s.name,s.version,s.owner_id,s.updated_at FROM secrets s LEFT JOIN grants g ON g.secret_id=s.id WHERE s.owner_id=%s OR g.user_id=%s ORDER BY s.updated_at DESC''',(a['id'],a['id'])).fetchall()
        return [dict(r) for r in rows]
